package com.sordanow.manualstatetracker;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Where the active state's name is drawn, relative to its image.
 */
@AllArgsConstructor
@Getter
public enum StateNamePosition
{
	HIDDEN("Hidden"),
	ABOVE("Above the image"),
	BELOW("Below the image");

	private final String displayName;

	public boolean isVisible()
	{
		return this != HIDDEN;
	}

	@Override
	public String toString()
	{
		return displayName;
	}
}
